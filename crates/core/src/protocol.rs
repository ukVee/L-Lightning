//! ELK-BLEDOM 9-byte command packets. All framed `0x7E ... 0xEF`.
//!
//! Protocol reverse-engineered from the Home Assistant community write-ups;
//! verified in the POC (`poc/`).

pub fn power_on() -> [u8; 9] {
    [0x7E, 0x00, 0x04, 0xF0, 0x00, 0x01, 0xFF, 0x00, 0xEF]
}

pub fn power_off() -> [u8; 9] {
    [0x7E, 0x00, 0x04, 0x00, 0x00, 0x00, 0xFF, 0x00, 0xEF]
}

pub fn set_color(r: u8, g: u8, b: u8) -> [u8; 9] {
    [0x7E, 0x00, 0x05, 0x03, r, g, b, 0x00, 0xEF]
}

pub fn set_brightness(pct: u8) -> [u8; 9] {
    [0x7E, 0x00, 0x01, pct, 0x00, 0x00, 0x00, 0x00, 0xEF]
}
